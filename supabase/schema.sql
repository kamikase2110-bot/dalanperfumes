begin;

create table if not exists public.products (
    id bigint generated by default as identity primary key,
    referencia text,
    nombre text not null check (length(trim(nombre)) between 1 and 500),
    marca text not null default '',
    "tipoStock" smallint not null default 0 check ("tipoStock" in (0, 1, 2)),
    inspiracion text not null default '',
    notas text not null default '',
    imagen text not null default 'Imagen no disponible',
    presentacion text not null default '' check (length(presentacion) <= 100),
    imagenes jsonb not null default '[]' check (jsonb_typeof(imagenes) = 'array' and jsonb_array_length(imagenes) <= 4),
    "precioUSD" numeric(12, 4) not null check ("precioUSD" >= 0 and "precioUSD" <= 100000),
    categoria text not null default 'perfume' check (categoria in ('perfume', 'desodorante', 'mini', 'splash', 'locion')),
    oculto boolean not null default false,
    version integer not null default 1 check (version > 0)
);

create unique index if not exists products_referencia_unique
    on public.products (referencia) where referencia is not null;

alter table public.products enable row level security;
revoke all on public.products from anon, authenticated;
grant all on public.products to service_role;
grant usage, select on sequence public.products_id_seq to service_role;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('product-images', 'product-images', true, 4194304,
    array['image/jpeg', 'image/png', 'image/webp'])
on conflict (id) do nothing;

commit;
